static bool
is_switch_layout_key(guint sym) {
    return sym == XKB_KEY_ISO_First_Group || sym == XKB_KEY_ISO_Last_Group || sym == XKB_KEY_ISO_Next_Group || sym == XKB_KEY_ISO_Prev_Group ||
           sym == XKB_KEY_Mode_switch;
}

static bool
is_keypad_sym(guint sym) {
    return XKB_KEY_KP_Space <= sym && sym <= XKB_KEY_KP_9;
}

static const char *
format_mods(int mods) {
    static char buf[128];
    char *p = buf, *s;
#define pr(x) p += snprintf(p, sizeof(buf) - (p - buf) - 1, "%s", x)
    pr("mods: ");
    s = p;
    if (mods & GLFW_MOD_CONTROL) pr("ctrl+");
    if (mods & GLFW_MOD_ALT) pr("alt+");
    if (mods & GLFW_MOD_SHIFT) pr("shift+");
    if (mods & GLFW_MOD_SUPER) pr("super+");
    if (mods & GLFW_MOD_META) pr("meta+");
    if (mods & GLFW_MOD_HYPER) pr("hyper+");
    if (mods & GLFW_MOD_CAPS_LOCK) pr("capslock+");
    if (mods & GLFW_MOD_NUM_LOCK) pr("numlock+");
    if (p == s) pr("none");
    else p--;
    pr(" ");
#undef pr
    return buf;
}

int
_glfwGtkModsFromState(GdkModifierType state, GdkDevice *device) {
    int mods = 0;
    if (state & GDK_SHIFT_MASK) mods |= GLFW_MOD_SHIFT;
    if (state & GDK_CONTROL_MASK) mods |= GLFW_MOD_CONTROL;
    if (state & GDK_ALT_MASK) mods |= GLFW_MOD_ALT;
    if (state & GDK_SUPER_MASK) mods |= GLFW_MOD_SUPER;
    // GDK reports Meta along with Alt and Hyper along with Super with the
    // usual keymaps. kitty's xkb code ignores Meta and Hyper by default too.
    if (state & GDK_LOCK_MASK) mods |= GLFW_MOD_CAPS_LOCK;
    if (device && gdk_device_get_num_lock_state(device)) mods |= GLFW_MOD_NUM_LOCK;
    return _glfwApplyModifierRemap(mods);
}

// GDK reports the modifier state from before the event. Native Wayland
// (wl_keyboard.modifiers arrives after wl_keyboard.key) behaves the same,
// so this is only used when KITTY_GTK_MODS_AFTER_EVENT is set, see the report.
static int
modifier_for_keysym(guint sym) {
    switch (sym) {
        case XKB_KEY_Shift_L:
        case XKB_KEY_Shift_R: return GLFW_MOD_SHIFT;
        case XKB_KEY_Control_L:
        case XKB_KEY_Control_R: return GLFW_MOD_CONTROL;
        case XKB_KEY_Alt_L:
        case XKB_KEY_Alt_R: return GLFW_MOD_ALT;
        case XKB_KEY_Super_L:
        case XKB_KEY_Super_R: return GLFW_MOD_SUPER;
        default: return 0;
    }
}

static guint
translate(GdkDisplay *display, guint keycode, GdkModifierType state, int layout) {
    guint keyval = 0;
    if (!gdk_display_translate_key(display, keycode, state, layout, &keyval, NULL, NULL, NULL)) return 0;
    return keyval;
}

static void
send_text(_GLFWwindow *w, const char *text, GLFWIMEState ime_state) {
    if (w && w->callbacks.keyboard) {
        GLFWkeyevent fake_ev = {.action = text ? GLFW_PRESS : GLFW_RELEASE};
        fake_ev.text = text;
        fake_ev.ime_state = ime_state;
        w->callbacks.keyboard((GLFWwindow *)w, &fake_ev);
    }
}

void
_glfwGtkHandleKeyEvent(_GLFWwindow *window, GdkEvent *event, bool is_press) {
    static char key_text[64];
    key_text[0] = 0;
    GdkDisplay *display = gdk_event_get_display(event);
    const guint keycode = gdk_key_event_get_keycode(event);
    const guint event_sym = gdk_key_event_get_keyval(event);
    const GdkModifierType state = gdk_event_get_modifier_state(event);
    const int layout = (int)gdk_key_event_get_layout(event);
    GdkDevice *device = gdk_event_get_device(event);
    int mods = _glfwGtkModsFromState(state, device);
    if (getenv("KITTY_GTK_MODS_AFTER_EVENT")) {
        int m = modifier_for_keysym(event_sym);
        if (is_press) mods |= m;
        else mods &= ~m;
    }
    debug(
        "%s keycode: 0x%x keyval: 0x%x (%s) layout: %d ",
        is_press ? "\x1b[31mPress\x1b[m" : "\x1b[32mRelease\x1b[m",
        keycode,
        event_sym,
        gdk_keyval_name(event_sym),
        layout);

    // The input method gets the key first, see the IME section below
    bool handled_by_ime = false;
    if (window->gtk.im_context) {
        free(window->gtk.ime.commit);
        window->gtk.ime.commit = NULL;
        window->gtk.ime.in_key_press = is_press;
        handled_by_ime = gtk_im_context_filter_keypress(window->gtk.im_context, event);
        window->gtk.ime.in_key_press = false;
    }
    const char *committed = window->gtk.ime.commit;
    if (handled_by_ime && !committed) {
        // A dead key, compose sequence or input method preedit in progress
        debug("handled by input method, ignoring\n");
        return;
    }

    const GdkModifierType known_mods = GDK_SHIFT_MASK | GDK_LOCK_MASK | GDK_CONTROL_MASK | GDK_ALT_MASK | GDK_SUPER_MASK | GDK_HYPER_MASK | GDK_META_MASK;
    guint clean_sym = translate(display, keycode, 0, layout);
    guint sym = clean_sym;
    // Use the event keysym when modifiers kitty does not report (such as
    // ISO_Level3_Shift aka AltGr) changed it, like xkb_glfw.c does with
    // consumed unknown modifiers.
    guint known_sym = translate(display, keycode, state & known_mods, layout);
    if (known_sym != event_sym || is_switch_layout_key(event_sym)) sym = event_sym;
    if ((mods & GLFW_MOD_NUM_LOCK) && is_keypad_sym(sym)) sym = event_sym;
    if (!sym) sym = event_sym;
    if (is_switch_layout_key(sym)) {
        debug("is a keyboard layout shift key, ignoring.\n");
        return;
    }

    GLFWkeyevent glfw_ev = {.action = is_press ? GLFW_PRESS : GLFW_RELEASE, .native_key_id = keycode};
    if (is_press) {
        if (committed) {
            // Text from the input method, which also does dead keys and compose
            strncpy(key_text, committed, sizeof(key_text) - 1);
            key_text[sizeof(key_text) - 1] = 0;
            gunichar first = g_utf8_get_char_validated(committed, -1);
            const char *next = g_utf8_next_char(committed);
            if (first != (gunichar)-1 && first != (gunichar)-2 && *next == 0 && first != gdk_keyval_to_unicode(event_sym)) {
                // A composed character, report it as the key, like xkb does
                guint composed = gdk_unicode_to_keyval(first);
                if (composed) sym = composed;
            }
        } else if (((GLFW_MOD_CONTROL | GLFW_MOD_ALT | GLFW_MOD_SUPER | GLFW_MOD_HYPER | GLFW_MOD_META) & mods) == 0) {
            // No input method, or it did not want the key
            gunichar ch = gdk_keyval_to_unicode(event_sym);
            if (ch) key_text[g_unichar_to_utf8(ch, key_text)] = 0;
        }
        if ((1 <= key_text[0] && key_text[0] <= 31) || key_text[0] == 127) key_text[0] = 0;
    }

    glfw_ev.key = _glfwGtkKeyForSym(sym);
    glfw_ev.native_key = sym;
    if (event_sym != sym && event_sym) glfw_ev.shifted_key = _glfwGtkKeyForSym(event_sym);
    if (layout != 0) {
        guint alternate = translate(display, keycode, 0, 0);
        if (alternate && alternate != sym) glfw_ev.alternate_key = _glfwGtkKeyForSym(alternate);
    }
    glfw_ev.mods = mods;
    glfw_ev.text = key_text;
    debug(
        "%sglfw_key: %u (%s) keysym: 0x%x (%s) shifted: %u alternate: %u text: %s\n",
        format_mods(mods),
        glfw_ev.key,
        _glfwGetKeyName(glfw_ev.key),
        sym,
        gdk_keyval_name(sym),
        glfw_ev.shifted_key,
        glfw_ev.alternate_key,
        key_text);
    _glfwInputKeyboard(window, &glfw_ev);
}

